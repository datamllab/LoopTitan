// The two text files for language models at the base, after llmstxt.org: llms.txt (src/llms.md, then every
// documentation page with its description) and llms-full.txt (the same, then the full text of every page).
// Site links in the pages become absolute URLs of the published site.
import fs from 'node:fs';
import path from 'node:path';
import { getCollection } from 'astro:content';
import { BASE, GROUPS } from '../../nav.mjs';

const intro = fs.readFileSync(path.resolve(process.cwd(), 'src/llms.md'), 'utf8').trim();

async function pages(site) {
	const root = new URL(BASE, site).href;
	const entries = new Map((await getCollection('docs')).map((e) => [e.id.replace(/^docs\/?/, ''), e]));
	const out = [];
	for (const g of GROUPS) {
		for (const [, slug, label] of g.pages) {
			const e = entries.get(slug);
			if (!e) throw new Error(`llms: no documentation page for slug '${slug}'`);
			out.push({ group: g.label, label, title: e.data.title, description: e.data.description, url: `${root}docs/${slug ? `${slug}/` : ''}`, body: e.body ?? '', synced: Boolean(slug) });
		}
	}
	return { root, pages: out };
}

function index(root, list) {
	const lines = ['## Documentation', ''];
	for (const p of list) lines.push(`- [${p.label}](${p.url}): ${p.description}`);
	lines.push('', '## Optional', '');
	lines.push(`- [Full text of the documentation](${root}llms-full.txt): every page above in one file`);
	lines.push('- [README](https://github.com/datamllab/LoopTitan/blob/main/README.md): quick start, results table and references');
	lines.push('- [CITATION.cff](https://github.com/datamllab/LoopTitan/blob/main/CITATION.cff): the citation');
	return lines.join('\n');
}

export async function llmsTxt(site) {
	const { root, pages: list } = await pages(site);
	return `${intro}\n\n${index(root, list)}\n`;
}

export async function llmsFullTxt(site) {
	const { root, pages: list } = await pages(site);
	const abs = (md) => md.replaceAll(`](${BASE}`, `](${root}`).replace(/^<!-- Generated by [^\n]*-->\n+/, '');
	const docs = list
		.filter((p) => p.synced)
		.map((p) => `# ${p.title}\n\nURL: ${p.url}\n\n${abs(p.body).trim()}`)
		.join('\n\n---\n\n');
	return `${intro}\n\n${index(root, list)}\n\n---\n\n${docs}\n`;
}
